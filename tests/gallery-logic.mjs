import assert from 'node:assert/strict';
import * as gallery from '../src/gallery-scene.js';
assert.equal(typeof gallery.cameraPosition, 'function', 'The camera position calculation must be available');
assert.equal(gallery.cameraPosition(0, 1000), 1);
assert.equal(gallery.cameraPosition(500, 1000), 57);
assert.equal(gallery.cameraPosition(1000, 1000), 113);
assert.equal(gallery.cameraPosition(-10, 1000), 1);
assert.equal(gallery.cameraPosition(2000, 1000), 113);
assert.equal(gallery.cameraPosition(0, 0), 1);
console.log('PASS camera travel remains bounded and follows scrolling');
